const pct = (x: number, lang: Lang) => {
  const v = (x * 100).toFixed(1);
  return lang === 'en' ? `${v}%` : lang === 'fr' ? `${v.replace('.', ',')} %` : `${v.replace('.', ',')}%`;
};
const points = (x: number, lang: Lang) => {
  const v = `${x >= 0 ? '+' : '−'}${Math.abs(x * 100).toFixed(1)}`;
  return lang === 'en' ? v : v.replace('.', ',');
};

